"""
PDF report generator using ReportLab
"""

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch, cm
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
)
from reportlab.lib.enums import TA_CENTER, TA_LEFT
import json
from datetime import datetime
import io


SEVERITY_COLORS = {
    'LOW':      colors.HexColor('#22c55e'),
    'MEDIUM':   colors.HexColor('#f59e0b'),
    'HIGH':     colors.HexColor('#ef4444'),
    'CRITICAL': colors.HexColor('#7c3aed'),
    'UNKNOWN':  colors.HexColor('#6b7280'),
}


def generate_pdf_report(prediction, user, disease_row) -> bytes:
    buf  = io.BytesIO()
    doc  = SimpleDocTemplate(buf, pagesize=A4,
                             leftMargin=1.5*cm, rightMargin=1.5*cm,
                             topMargin=2*cm, bottomMargin=2*cm)
    styles = getSampleStyleSheet()
    story  = []

    # ── Header ────────────────────────────────────────────────────────────────
    title_style = ParagraphStyle('Title', parent=styles['Title'],
                                 fontSize=22, textColor=colors.HexColor('#1e40af'),
                                 spaceAfter=6)
    sub_style   = ParagraphStyle('Sub', parent=styles['Normal'],
                                 fontSize=11, textColor=colors.HexColor('#64748b'),
                                 alignment=TA_CENTER)
    body_style  = ParagraphStyle('Body', parent=styles['Normal'],
                                 fontSize=10, leading=16)
    label_style = ParagraphStyle('Label', parent=styles['Normal'],
                                 fontSize=9, textColor=colors.HexColor('#6b7280'))
    value_style = ParagraphStyle('Value', parent=styles['Normal'],
                                 fontSize=11, fontName='Helvetica-Bold')
    warn_style  = ParagraphStyle('Warn', parent=styles['Normal'],
                                 fontSize=10, textColor=colors.white,
                                 backColor=colors.HexColor('#ef4444'),
                                 borderPadding=8)

    story.append(Paragraph("🩺 MediCheck AI", title_style))
    story.append(Paragraph("Medical Symptom Checker – Prediction Report", sub_style))
    story.append(Spacer(1, 0.3*inch))
    story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor('#1e40af')))
    story.append(Spacer(1, 0.2*inch))

    # ── Disclaimer ────────────────────────────────────────────────────────────
    disc_style = ParagraphStyle('Disc', parent=styles['Normal'], fontSize=8,
                                textColor=colors.HexColor('#92400e'),
                                backColor=colors.HexColor('#fef3c7'),
                                borderPadding=6)
    story.append(Paragraph(
        "⚠️  DISCLAIMER: This report is generated by an AI system for educational purposes only. "
        "It is NOT a substitute for professional medical advice, diagnosis, or treatment. "
        "Always consult a qualified healthcare provider.", disc_style))
    story.append(Spacer(1, 0.2*inch))

    # ── Patient Info ──────────────────────────────────────────────────────────
    story.append(Paragraph("Patient Information", styles['Heading2']))
    info_data = [
        ['Patient Name', user.name],
        ['Email',        user.email],
        ['Report Date',  prediction.created_at.strftime('%B %d, %Y at %I:%M %p') if prediction.created_at else 'N/A'],
        ['Report ID',    f'MCR-{prediction.id:05d}'],
    ]
    info_table = Table(info_data, colWidths=[4*cm, 12*cm])
    info_table.setStyle(TableStyle([
        ('FONTNAME',  (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTSIZE',  (0, 0), (-1, -1), 10),
        ('ROWBACKGROUNDS', (0, 0), (-1, -1), [colors.HexColor('#f8fafc'), colors.white]),
        ('GRID',      (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ('PADDING',   (0, 0), (-1, -1), 6),
    ]))
    story.append(info_table)
    story.append(Spacer(1, 0.2*inch))

    # ── Prediction Result ─────────────────────────────────────────────────────
    story.append(Paragraph("Prediction Result", styles['Heading2']))
    severity     = disease_row.severity_level if disease_row else 'UNKNOWN'
    sev_color    = SEVERITY_COLORS.get(severity, colors.gray)
    confidence   = prediction.confidence_score

    result_data = [
        ['Predicted Disease', prediction.predicted_disease],
        ['Confidence Score',  f'{confidence:.1f}%'],
        ['Severity Level',    severity],
        ['Emergency',         'YES – Seek immediate medical help!' if (disease_row and disease_row.emergency) else 'No'],
    ]
    result_table = Table(result_data, colWidths=[5*cm, 11*cm])
    result_table.setStyle(TableStyle([
        ('FONTNAME',  (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTNAME',  (1, 0), (1, 0), 'Helvetica-Bold'),
        ('FONTSIZE',  (0, 0), (-1, -1), 10),
        ('ROWBACKGROUNDS', (0, 0), (-1, -1), [colors.HexColor('#eff6ff'), colors.white]),
        ('GRID',      (0, 0), (-1, -1), 0.5, colors.HexColor('#bfdbfe')),
        ('PADDING',   (0, 0), (-1, -1), 7),
        ('TEXTCOLOR', (1, 2), (1, 2), sev_color),
        ('FONTNAME',  (1, 2), (1, 2), 'Helvetica-Bold'),
    ]))
    story.append(result_table)
    story.append(Spacer(1, 0.15*inch))

    # Emergency banner
    if disease_row and disease_row.emergency:
        story.append(Paragraph(
            "🚨 EMERGENCY ALERT: This condition may require immediate medical attention. "
            "Please call emergency services or go to the nearest hospital.", warn_style))
        story.append(Spacer(1, 0.1*inch))

    # ── Description ───────────────────────────────────────────────────────────
    if disease_row and disease_row.description:
        story.append(Paragraph("About This Condition", styles['Heading2']))
        story.append(Paragraph(disease_row.description, body_style))
        story.append(Spacer(1, 0.15*inch))

    # ── Precautions ───────────────────────────────────────────────────────────
    if disease_row and disease_row.precautions:
        story.append(Paragraph("Recommended Precautions", styles['Heading2']))
        precs = disease_row.precautions.split(';')
        for i, p in enumerate(precs, 1):
            story.append(Paragraph(f"{i}. {p.strip()}", body_style))
        story.append(Spacer(1, 0.15*inch))

    # ── Reported Symptoms ─────────────────────────────────────────────────────
    story.append(Paragraph("Reported Symptoms", styles['Heading2']))
    symptoms = json.loads(prediction.selected_symptoms)
    sym_text = ', '.join(s.replace('_', ' ').title() for s in symptoms)
    story.append(Paragraph(sym_text, body_style))
    story.append(Spacer(1, 0.15*inch))

    # ── Alternative Predictions ───────────────────────────────────────────────
    story.append(Paragraph("Alternative Predictions (Top 5)", styles['Heading2']))
    all_probs = json.loads(prediction.all_probabilities)
    alt_data  = [['Rank', 'Disease', 'Probability']]
    for i, item in enumerate(all_probs, 1):
        alt_data.append([str(i), item['disease'], f"{item['probability']:.1f}%"])
    alt_table = Table(alt_data, colWidths=[1.5*cm, 11*cm, 4*cm])
    alt_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1e40af')),
        ('TEXTCOLOR',  (0, 0), (-1, 0), colors.white),
        ('FONTNAME',   (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE',   (0, 0), (-1, -1), 9),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.HexColor('#f8fafc'), colors.white]),
        ('GRID',       (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ('PADDING',    (0, 0), (-1, -1), 6),
        ('ALIGN',      (2, 0), (2, -1), 'CENTER'),
    ]))
    story.append(alt_table)
    story.append(Spacer(1, 0.3*inch))

    # ── Footer ────────────────────────────────────────────────────────────────
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#e2e8f0')))
    footer_style = ParagraphStyle('Footer', parent=styles['Normal'],
                                  fontSize=8, textColor=colors.HexColor('#94a3b8'),
                                  alignment=TA_CENTER)
    story.append(Spacer(1, 0.1*inch))
    story.append(Paragraph(
        f"Generated by MediCheck AI | {datetime.now().strftime('%Y-%m-%d %H:%M')} | "
        "This report is for educational purposes only and does not constitute medical advice.",
        footer_style))

    doc.build(story)
    buf.seek(0)
    return buf.read()
